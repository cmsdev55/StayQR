// Builds the ScanGlobe land mask: a 2°-cell equirectangular bitmap of land, base64-encoded.
// Usage: node scripts/gen-land-mask.mjs  → src/components/three/land-mask.ts (commit the output)
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
const require = createRequire(import.meta.url);
const { feature } = require("topojson-client");
const { geoContains } = require("d3-geo");
const land = feature(require("world-atlas/land-50m.json"), "land");

const W = 180, H = 90; // 2° cells
const bits = new Uint8Array(Math.ceil((W * H) / 8));
let count = 0;
for (let y = 0; y < H; y++) {
  const lat = 90 - (y + 0.5) * (180 / H);
  for (let x = 0; x < W; x++) {
    const lon = -180 + (x + 0.5) * (360 / W);
    if (geoContains(land, [lon, lat])) {
      const i = y * W + x;
      bits[i >> 3] |= 1 << (i & 7);
      count++;
    }
  }
}
const b64 = Buffer.from(bits).toString("base64");
writeFileSync(
  "src/components/three/land-mask.ts",
  `// Generated by scripts/gen-land-mask.mjs from Natural Earth 1:50m land (world-atlas). Do not edit.\n` +
    `export const LAND_W = ${W};\nexport const LAND_H = ${H};\nexport const LAND_BITS = "${b64}";\n`,
);
console.log("land cells", count, "of", W * H, "→", b64.length, "base64 chars");
